import argparse
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


parser = argparse.ArgumentParser()
parser.add_argument("--root", type=Path, required=True)
args = parser.parse_args()

root = args.root
df = pd.read_csv(root / "all_directions.csv")

required = {
    "direction_seed",
    "perturbation_coefficient",
    "reward",
}
if not required.issubset(df.columns):
    raise ValueError(f"CSV 缺少列：{required - set(df.columns)}")

if df.duplicated(
    ["direction_seed", "perturbation_coefficient"]
).any():
    raise ValueError("同一方向、同一坐标有重复结果")

# 排除恢复脚本中标记的填补点
keep = np.ones(len(df), dtype=bool)

for path in root.glob("dirseed_*/recovery_metadata.json"):
    metadata = json.loads(path.read_text(encoding="utf-8"))
    seed = int(path.parent.name.removeprefix("dirseed_"))
    coefficient = metadata["imputed_point"][
        "perturbation_coefficient"
    ]

    imputed = (
        df["direction_seed"].eq(seed).to_numpy()
        & np.isclose(
            df["perturbation_coefficient"].to_numpy(float),
            coefficient,
            rtol=0,
            atol=1e-8,
        )
    )
    keep &= ~imputed
    print(f"排除填补点：seed={seed}, coefficient={coefficient}")

df = df.loc[keep].copy()

# 按坐标对不同方向求平均；std 为方向之间的样本标准差
summary = (
    df.groupby("perturbation_coefficient")["reward"]
    .agg(
        mean_reward="mean",
        direction_std="std",
        num_directions="count",
    )
    .reset_index()
    .sort_values("perturbation_coefficient")
)

summary.to_csv(root / "mean_direction.csv", index=False)

x = summary["perturbation_coefficient"].to_numpy(float)
y = summary["mean_reward"].to_numpy(float)
std = summary["direction_std"].to_numpy(float)

fig, ax = plt.subplots(figsize=(8, 5))

line, = ax.plot(
    x,
    y,
    "o-",
    linewidth=2,
    label="Mean across directions",
)

ax.fill_between(
    x,
    np.clip(y - std, 0, 1),
    np.clip(y + std, 0, 1),
    color=line.get_color(),
    alpha=0.2,
    label="±1 SD across directions",
)

ax.axvline(0, color="black", linestyle="--", linewidth=1)
ax.set_xlabel("Perturbation coefficient")
ax.set_ylabel("Mean reward")
ax.set_title("Reward landscape averaged across directions")
ax.set_ylim(0, 1.1)
ax.grid(alpha=0.3)
ax.legend()
fig.tight_layout()

fig.savefig(root / "mean_direction.png", dpi=300)
plt.close(fig)

print(summary.to_string(index=False))
print(f"\n保存到：{root / 'mean_direction.png'}")